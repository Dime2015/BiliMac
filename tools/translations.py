def esc(s): return s.replace('\\', '\\\\').replace('"', '\\"')

def source_keys(root):
    keys = []
    for f in sorted(glob.glob(os.path.join(root, "Sources/BiliMac/*.swift"))):
        for m in re.finditer(r'\bLf?\("((?:[^"\\]|\\.)*)"', open(f).read()):
            k = m.group(1).encode().decode('unicode_escape').encode('latin1').decode('utf-8') if '\\' in m.group(1) else m.group(1)
            if k not in keys: keys.append(k)
    for k in ["推荐", "热门", "排行榜", "历史", "稍后再看", "收藏夹", "通用", "线路", "播放", "信息显示", "弹幕", "账号", "快捷键"]:
        if k not in keys: keys.append(k)
    return keys

if __name__ == "__main__":
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    keys = source_keys(root)
    missing = [k for k in keys if k not in T]
    if missing:
        print("MISSING TRANSLATIONS:", json.dumps(missing, ensure_ascii=False)); sys.exit(1)
    for lang, idx in (("zh-Hans", None), ("en", 0), ("ja", 1)):
        d = os.path.join(root, "Resources", f"{lang}.lproj"); os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, "Localizable.strings"), "w") as f:
            f.write("/* Generated by tools/translations.py — edit there. */\n")
            for k in keys:
                v = k if idx is None else T[k][idx]
                f.write(f'"{esc(k)}" = "{esc(v)}";\n')
    print(f"wrote {len(keys)} keys × 3 languages")
